# 辅助函数: 对数插值实验 IDT / LFS (用于 GA 目标函数)
# ============================================================

def interp_loglog(xs, ys, x):
    """log-log 插值 (x>0, y>0)"""
    xs = np.asarray(xs, dtype=float)
    ys = np.asarray(ys, dtype=float)
    x = float(x)
    if x <= xs.min() or x >= xs.max():
        return np.nan  # 超出实验范围不评估
    return float(np.exp(np.interp(np.log(x), np.log(xs), np.log(ys))))


def interp_loglin(xs, ys, x):
    """x 线性, y 对数插值 (用于 LFS vs phi)"""
    xs = np.asarray(xs, dtype=float)
    ys = np.asarray(ys, dtype=float)
    x = float(x)
    if x < xs.min() or x > xs.max():
        return np.nan
    return float(np.exp(np.interp(x, xs, np.log(ys))))


def chen_idt_target(XH2, P_atm, T):
    """Chen et al. [42] 实验 IDT (s), log-log 插值; 超范围返回 nan"""
    table = IDT_CHEN_1_2ATM if P_atm < 5 else IDT_CHEN_10ATM
    if XH2 not in table:
        return np.nan
    pts = table[XH2]
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    val_ms = interp_loglog(xs, ys, 1000.0 / T)
    return val_ms * 1e-3 if np.isfinite(val_ms) else np.nan


def lfs_exp_target(XH2, Tu, P_atm, phi):
    """实验 LFS (m/s) 插值, 优先精确匹配 (XH2,Tu,P) 组合"""
    # Fig. 15 数据 (XH2, Tu) 精确组合
    if (round(XH2, 2), float(Tu)) in LFS_FIG15 and abs(P_atm - 1.0) < 1e-6:
        pts = LFS_FIG15[(round(XH2, 2), float(Tu))]
        v = interp_loglin([p[0] for p in pts], [p[1] for p in pts], phi)
        return v / 100.0 if np.isfinite(v) else np.nan
    # Fig. 11/12: 298K, 1atm, phi 扫描
    if abs(Tu - 298.0) < 1e-6 and abs(P_atm - 1.0) < 1e-6 and round(XH2, 2) in LFS_298K_1ATM:
        pts = LFS_298K_1ATM[round(XH2, 2)]
        v = interp_loglin([p[0] for p in pts], [p[1] for p in pts], phi)
        return v / 100.0 if np.isfinite(v) else np.nan
    # Fig. 13: phi=1, 298K, XH2 扫描
    if abs(Tu - 298.0) < 1e-6 and abs(phi - 1.0) < 1e-6 and P_atm in LFS_ICHIKAWA:
        pts = LFS_ICHIKAWA[P_atm]
        v = interp_loglin([p[0] for p in pts], [p[1] for p in pts], XH2)
        return v / 100.0 if np.isfinite(v) else np.nan
    # Fig. 14: XH2=0.4, 298K, phi 扫描
    if abs(Tu - 298.0) < 1e-6 and abs(XH2 - 0.4) < 1e-6 and P_atm in LFS_SHRESTHA:
        pts = LFS_SHRESTHA[P_atm]
        v = interp_loglin([p[0] for p in pts], [p[1] for p in pts], phi)
        return v / 100.0 if np.isfinite(v) else np.nan
    return np.nan


